function assessBiodiversity(input: BiodiversityAssessmentInput): BiodiversityAssessmentResult {
  const rng = createRngFromInput(input)
  const assessmentId = 'BA-' + randInt(rng, 10000, 99999)

  const taxaGroups = input.taxa_groups.length > 0 ? input.taxa_groups : ['Mammals', 'Birds', 'Reptiles', 'Amphibians', 'Fish', 'Invertebrates', 'Plants', 'Fungi']
  const depthMultiplier = input.assessment_depth === 'comprehensive' ? 1.5 : input.assessment_depth === 'standard' ? 1.0 : 0.6

  const taxaRecords: TaxonRecord[] = []
  for (const group of taxaGroups) {
    const baseCount = randInt(rng, 10, 200)
    const speciesCount = Math.round(baseCount * depthMultiplier)
    const endemicCount = Math.round(speciesCount * randFloat(rng, 0.02, 0.25))
    const threatenedCount = Math.round(speciesCount * randFloat(rng, 0.01, 0.15))

    taxaRecords.push({
      group,
      species_count: speciesCount,
      endemic_count: endemicCount,
      threatened_count: threatenedCount,
      shannon_index: randFloat(rng, 1.5, 4.5),
      simpson_index: randFloat(rng, 0.6, 0.95),
      evenness: randFloat(rng, 0.5, 0.9),
      key_species: pickN(rng, ['Keystone predator', 'Ecosystem engineer', 'Pollinator', 'Seed disperser', 'Umbrella species', 'Flagship species', 'Indicator species'], randInt(rng, 1, 3)),
    })
  }

  const ecosystemServices: EcosystemService[] = [
    { service: 'Carbon Sequestration', value_category: 'Regulating', estimated_value_usd_ha_yr: randInt(rng, 50, 500), trend: pick(rng, ['Improving', 'Stable', 'Declining'] as const), confidence: pick(rng, ['High', 'Medium', 'Low'] as const) },
    { service: 'Water Purification', value_category: 'Regulating', estimated_value_usd_ha_yr: randInt(rng, 30, 300), trend: pick(rng, ['Improving', 'Stable', 'Declining'] as const), confidence: pick(rng, ['High', 'Medium', 'Low'] as const) },
    { service: 'Pollination Services', value_category: 'Supporting', estimated_value_usd_ha_yr: randInt(rng, 20, 200), trend: pick(rng, ['Improving', 'Stable', 'Declining'] as const), confidence: pick(rng, ['High', 'Medium', 'Low'] as const) },
    { service: 'Soil Formation & Fertility', value_category: 'Supporting', estimated_value_usd_ha_yr: randInt(rng, 10, 100), trend: pick(rng, ['Improving', 'Stable', 'Declining'] as const), confidence: pick(rng, ['High', 'Medium', 'Low'] as const) },
    { service: 'Flood Regulation', value_category: 'Regulating', estimated_value_usd_ha_yr: randInt(rng, 40, 400), trend: pick(rng, ['Improving', 'Stable', 'Declining'] as const), confidence: pick(rng, ['High', 'Medium', 'Low'] as const) },
    { service: 'Recreation & Ecotourism', value_category: 'Cultural', estimated_value_usd_ha_yr: randInt(rng, 100, 1000), trend: pick(rng, ['Improving', 'Stable', 'Declining'] as const), confidence: pick(rng, ['High', 'Medium', 'Low'] as const) },
    { service: 'Timber & Non-timber Products', value_category: 'Provisioning', estimated_value_usd_ha_yr: randInt(rng, 20, 250), trend: pick(rng, ['Improving', 'Stable', 'Declining'] as const), confidence: pick(rng, ['High', 'Medium', 'Low'] as const) },
    { service: 'Genetic Resources', value_category: 'Provisioning', estimated_value_usd_ha_yr: randInt(rng, 5, 80), trend: pick(rng, ['Improving', 'Stable', 'Declining'] as const), confidence: pick(rng, ['High', 'Medium', 'Low'] as const) },
  ]

  const totalSpecies = taxaRecords.reduce((s, t) => s + t.species_count, 0)
  const totalEndemic = taxaRecords.reduce((s, t) => s + t.endemic_count, 0)
  const totalThreatened = taxaRecords.reduce((s, t) => s + t.threatened_count, 0)
  const avgShannon = taxaRecords.reduce((s, t) => s + t.shannon_index, 0) / taxaRecords.length
  const avgSimpson = taxaRecords.reduce((s, t) => s + t.simpson_index, 0) / taxaRecords.length

  const biodiversityIndices: Record<string, number> = {
    total_species_richness: totalSpecies,
    endemic_species_count: totalEndemic,
    threatened_species_count: totalThreatened,
    mean_shannon_wiener: Math.round(avgShannon * 100) / 100,
    mean_simpson_diversity: Math.round(avgSimpson * 100) / 100,
    species_density_per_km2: Math.round(totalSpecies / input.survey_area_km2 * 100) / 100,
    endemism_rate: Math.round(totalEndemic / totalSpecies * 10000) / 100,
    threat_prevalence: Math.round(totalThreatened / totalSpecies * 10000) / 100,
  }

  const threatAssessment: string[] = []
  threatAssessment.push(totalThreatened + ' threatened species identified across ' + taxaGroups.length + ' taxa groups')
  if (totalEndemic > 0) threatAssessment.push(totalEndemic + ' endemic species - high conservation value for ' + input.region)
  threatAssessment.push('Species density: ' + (totalSpecies / input.survey_area_km2).toFixed(1) + ' species/km2')
  const decliningServices = ecosystemServices.filter(s => s.trend === 'Declining')
  if (decliningServices.length > 0) {
    threatAssessment.push(decliningServices.length + ' ecosystem services showing declining trends')
  }
  threatAssessment.push('Primary threats: Habitat fragmentation, Invasive species, Climate change, Overexploitation')

  const ecosystemIntegrity = Math.round((avgShannon / 4.5 * 40 + avgSimpson * 30 + (1 - totalThreatened / totalSpecies) * 30))

  const comparisonToReference: string[] = []
  if (input.reference_condition === 'pristine') {
    comparisonToReference.push('Current species richness: ' + randInt(rng, 50, 85) + '% of pristine reference condition')
    comparisonToReference.push('Functional diversity: ' + randInt(rng, 40, 80) + '% of expected pristine levels')
  } else if (input.reference_condition === 'historical') {
    comparisonToReference.push('Species richness change: ' + randInt(rng, -40, 10) + '% compared to historical baseline')
    comparisonToReference.push('Community composition shift: ' + randInt(rng, 15, 60) + '% turnover from historical state')
  } else {
    comparisonToReference.push('Current condition: ' + randInt(rng, 60, 90) + '% of best available reference site')
    comparisonToReference.push('Recovery potential: ' + randInt(rng, 50, 95) + '% achievable with active restoration')
  }
  comparisonToReference.push('Beta diversity across sites: ' + randFloat(rng, 0.3, 0.8).toFixed(2) + ' (moderate to high heterogeneity)')

  const managementRecommendations: string[] = []
  managementRecommendations.push('Expand protected area network to cover ' + totalEndemic + ' endemic species habitats')
  managementRecommendations.push('Implement species recovery plans for ' + totalThreatened + ' threatened species')
  managementRecommendations.push('Restore degraded habitats to improve Shannon index by target of 0.5')
  managementRecommendations.push('Establish ex-situ conservation for critically endangered endemics')
  managementRecommendations.push('Monitor ' + decliningServices.length + ' declining ecosystem services with quarterly assessments')
  managementRecommendations.push('Control invasive species in ' + randInt(rng, 2, 6) + ' priority zones')

  return {
    assessment_id: assessmentId,
    region: input.region,
    ecosystem_type: input.ecosystem_type,
    survey_area_km2: input.survey_area_km2,
    taxa_records: taxaRecords,
    ecosystem_services: ecosystemServices,
    biodiversity_indices: biodiversityIndices,
    threat_assessment: threatAssessment,
    ecosystem_integrity_score: ecosystemIntegrity,
    comparison_to_reference: comparisonToReference,
    management_recommendations: managementRecommendations,
  }
}

