function runPoachingPrevention(input: PoachingPreventionInput): PoachingPreventionResult {
  const rng = createRngFromInput(input)
  const systemId = 'PP-' + randInt(rng, 10000, 99999)

  const threatTypes = ['Ivory poaching', 'Bushmeat hunting', 'Traditional medicine trade', 'Live animal capture', 'Skin/bone trade', 'Trophy poaching', 'Subsistence poaching', 'Organized crime poaching']
  const hotspotCount = randInt(rng, 3, 10)
  const hotspots: PoachingHotspot[] = []

  for (let i = 0; i < hotspotCount; i++) {
    const riskScore = randFloat(rng, 0.2, 0.98)
    const riskLevel = riskScore >= 0.8 ? 'Critical' : riskScore >= 0.6 ? 'High' : riskScore >= 0.4 ? 'Medium' : 'Low'
    const incidents = riskScore > 0.7 ? randInt(rng, 5, 25) : riskScore > 0.4 ? randInt(rng, 1, 8) : randInt(rng, 0, 3)

    hotspots.push({
      zone_id: 'HS-' + String(i + 1).padStart(3, '0'),
      risk_level: riskLevel,
      risk_score: riskScore,
      coordinates: [randFloat(rng, -180, 180), randFloat(rng, -90, 90)],
      primary_threat: pick(rng, threatTypes),
      incident_history_12mo: incidents,
      accessibility: pick(rng, ['Easy', 'Moderate', 'Difficult'] as const),
      recommended_patrol_frequency: riskScore > 0.7 ? 'Daily' : riskScore > 0.5 ? '3x/Weekly' : riskScore > 0.3 ? 'Weekly' : 'Bi-weekly',
    })
  }

  hotspots.sort((a, b) => b.risk_score - a.risk_score)

  const patrolRoutes: PatrolRoute[] = []
  const routeCount = randInt(rng, 3, 8)
  for (let i = 0; i < routeCount; i++) {
    const coveredHotspots = pickN(rng, hotspots, randInt(rng, 1, Math.min(3, hotspots.length)))
    patrolRoutes.push({
      route_id: 'PR-' + String(i + 1).padStart(3, '0'),
      priority: i + 1,
      waypoints: randInt(rng, 4, 12),
      estimated_duration_hours: randFloat(rng, 2, 10),
      coverage_km2: randFloat(rng, 5, 50),
      hotspot_coverage: coveredHotspots.map(h => h.zone_id),
      recommended_time: pick(rng, ['Dawn (05:00-08:00)', 'Morning (08:00-12:00)', 'Afternoon (12:00-17:00)', 'Dusk (17:00-20:00)', 'Night (20:00-05:00)']),
      risk_mitigation_score: randFloat(rng, 0.3, 0.9),
    })
  }

  const resourceAllocation: string[] = []
  const criticalHotspots = hotspots.filter(h => h.risk_level === 'Critical' || h.risk_level === 'High')
  resourceAllocation.push('Deploy ' + Math.ceil(criticalHotspots.length * 1.5) + ' additional ranger units to high-risk zones')
  resourceAllocation.push('Current patrol coverage: ' + input.patrol_coverage_percent + '% - Target: ' + Math.min(95, input.patrol_coverage_percent + 20) + '%')
  resourceAllocation.push('Ranger-to-area ratio: 1:' + Math.round(input.area_km2 / Math.max(1, input.ranger_count)) + ' km2 (recommended 1:25)')
  resourceAllocation.push('Allocate ' + randInt(rng, 2, 6) + ' rapid response teams for critical zones')
  resourceAllocation.push('Budget estimate: $' + randInt(rng, 50, 500) + 'K annually for enhanced patrol operations')

  const technologyRecommendations: string[] = []
  if (input.technology_level === 'basic' || input.technology_level === 'intermediate') {
    technologyRecommendations.push('Deploy camera trap network: ' + randInt(rng, 50, 200) + ' units across high-risk zones')
    technologyRecommendations.push('Implement drone surveillance: ' + randInt(rng, 2, 8) + ' UAVs for aerial monitoring')
  }
  if (input.technology_level === 'advanced' || input.technology_level === 'intermediate') {
    technologyRecommendations.push('Install acoustic gunshot detection system covering ' + randInt(rng, 50, 200) + ' km2')
    technologyRecommendations.push('Deploy AI-powered real-time camera trap analysis with species/poacher classification')
  }
  technologyRecommendations.push('Implement GPS tracking collars on ' + randInt(rng, 5, 20) + ' key individuals of target species')
  technologyRecommendations.push('Establish centralized command center with real-time data integration')
  technologyRecommendations.push('Deploy SMART (Spatial Monitoring and Reporting Tool) across all patrol teams')

  const communityStrategies: string[] = []
  if (input.community_engagement_level === 'low') {
    communityStrategies.push('Establish community conservancy partnerships in buffer zones')
    communityStrategies.push('Launch environmental education programs in ' + randInt(rng, 5, 15) + ' surrounding communities')
  }
  communityStrategies.push('Create incentive programs: ' + randInt(rng, 10, 30) + '% revenue sharing from ecotourism')
  communityStrategies.push('Train ' + randInt(rng, 20, 100) + ' community wildlife scouts for local monitoring')
  communityStrategies.push('Develop alternative livelihood programs to reduce poaching dependency')
  communityStrategies.push('Establish anonymous tip-line with reward system for poaching intelligence')

  const effectivenessProjection: string[] = []
  const currentEffectiveness = input.patrol_coverage_percent * 0.4 + (input.technology_level === 'advanced' ? 30 : input.technology_level === 'intermediate' ? 15 : 5) + (input.community_engagement_level === 'high' ? 20 : input.community_engagement_level === 'medium' ? 10 : 0)
  const projectedEffectiveness = Math.min(95, currentEffectiveness + randInt(rng, 15, 35))
  effectivenessProjection.push('Current prevention effectiveness: ' + currentEffectiveness.toFixed(0) + '%')
  effectivenessProjection.push('Projected effectiveness with recommendations: ' + projectedEffectiveness.toFixed(0) + '%')
  effectivenessProjection.push('Expected incident reduction: ' + randInt(rng, 30, 70) + '% within 12 months')
  effectivenessProjection.push('ROI of prevention investment: $' + randFloat(rng, 2, 8).toFixed(1) + ' return per $1 invested')

  const avgRisk = hotspots.reduce((s, h) => s + h.risk_score, 0) / hotspots.length
  const overallThreat = avgRisk >= 0.7 ? 'Critical' : avgRisk >= 0.5 ? 'High' : avgRisk >= 0.3 ? 'Medium' : 'Low'

  return {
    system_id: systemId,
    protected_area: input.protected_area,
    risk_assessment_date: '2025-' + String(randInt(rng, 1, 12)).padStart(2, '0') + '-' + String(randInt(rng, 1, 28)).padStart(2, '0'),
    overall_threat_level: overallThreat,
    hotspots,
    patrol_routes: patrolRoutes,
    resource_allocation: resourceAllocation,
    technology_recommendations: technologyRecommendations,
    community_strategies: communityStrategies,
    effectiveness_projection: effectivenessProjection,
  }
}

