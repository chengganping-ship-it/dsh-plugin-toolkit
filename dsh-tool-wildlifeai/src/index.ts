function analyzeCameraTraps(input: CameraTrapInput): CameraTrapResult {
  const rng = createRngFromInput(input)
  const analysisId = 'CT-' + randInt(rng, 10000, 99999)

  const trapNights = input.num_cameras * input.deployment_duration_days
  const speciesPool = input.target_species.length > 0 ? input.target_species : [
    'Leopard', 'Elephant', 'Buffalo', 'Duiker', 'Civet', 'Mongoose', 'Pangolin',
    'Gorilla', 'Chimpanzee', 'Forest Hog', 'Bongo', 'Golden Cat', 'Jackal', 'Hyena'
  ]

  const detectionCount = randInt(rng, Math.min(5, speciesPool.length), Math.min(speciesPool.length, 20))
  const selectedSpecies = pickN(rng, speciesPool, detectionCount)
  const detections: CameraTrapDetection[] = []

  for (const sp of selectedSpecies) {
    const detectionCount = randInt(rng, 3, 200)
    const rate = detectionCount / trapNights * 100
    detections.push({
      species: sp,
      detection_count: detectionCount,
      detection_rate_per_100trap_nights: Math.round(rate * 100) / 100,
      occupancy_probability: randFloat(rng, 0.1, 0.95),
      activity_pattern: pick(rng, ['Diurnal', 'Nocturnal', 'Crepuscular', 'Cathemeral'] as const),
      group_size_avg: randFloat(rng, 1, 8),
      confidence: randFloat(rng, 0.7, 0.99),
      independent_events: Math.round(detectionCount * randFloat(rng, 0.3, 0.7)),
    })
  }

  detections.sort((a, b) => b.detection_count - a.detection_count)

  const stationCount = Math.min(input.num_cameras, randInt(rng, 5, 20))
  const stations: CameraTrapStation[] = []
  for (let i = 0; i < stationCount; i++) {
    const operationalDays = input.deployment_duration_days - randInt(rng, 0, 15)
    stations.push({
      station_id: 'CAM-' + String(i + 1).padStart(3, '0'),
      coordinates: [randFloat(rng, -180, 180), randFloat(rng, -90, 90)],
      total_images: randInt(rng, 100, 10000),
      species_detected: randInt(rng, 1, detections.length),
      detection_rate: randFloat(rng, 0.5, 15),
      operational_days: operationalDays,
      malfunction_days: input.deployment_duration_days - operationalDays,
      top_species: pickN(rng, detections.map(d => d.species), randInt(rng, 1, 3)),
    })
  }

  const totalImages = stations.reduce((s, st) => s + st.total_images, 0)
  const speciesRichnessEstimate = Math.round(detections.length * randFloat(rng, 1.1, 1.5))

  const rarefactionCurve: string[] = []
  rarefactionCurve.push('Observed species: ' + detections.length + ' from ' + trapNights + ' trap-nights')
  rarefactionCurve.push('Estimated total species (Chao1): ' + speciesRichnessEstimate)
  rarefactionCurve.push('Sampling completeness: ' + randInt(rng, 60, 90) + '%')
  rarefactionCurve.push('Asymptote reached: ' + (rng() > 0.5 ? 'Yes - sampling adequate' : 'No - additional sampling recommended'))
  rarefactionCurve.push('Rare species (< 10 detections): ' + detections.filter(d => d.detection_count < 10).length)

  const detectionGaps: string[] = []
  const lowDetection = detections.filter(d => d.detection_rate_per_100trap_nights < 1)
  if (lowDetection.length > 0) {
    detectionGaps.push('Low detection rate species: ' + lowDetection.length + ' (< 1 per 100 trap-nights)')
  }
  const malfunctionStations = stations.filter(s => s.malfunction_days > 5)
  if (malfunctionStations.length > 0) {
    detectionGaps.push(malfunctionStations.length + ' stations had > 5 malfunction days - data gaps possible')
  }
  detectionGaps.push('Spatial coverage gap: ' + randInt(rng, 10, 40) + '% of target area not covered')
  detectionGaps.push('Temporal gap: Night coverage ' + randInt(rng, 70, 100) + '% | Day coverage ' + randInt(rng, 60, 100) + '%')

  const occupancyResults: string[] = []
  if (input.occupancy_modeling) {
    const highOccupancy = detections.filter(d => d.occupancy_probability >= 0.7)
    const lowOccupancy = detections.filter(d => d.occupancy_probability < 0.4)
    occupancyResults.push('High occupancy (Psi >= 0.7): ' + highOccupancy.length + ' species widely distributed')
    occupancyResults.push('Low occupancy (Psi < 0.4): ' + lowOccupancy.length + ' species rare or localized')
    occupancyResults.push('Mean detection probability (p): ' + randFloat(rng, 0.1, 0.5).toFixed(2))
    occupancyResults.push('Best covariate for occupancy: ' + pick(rng, ['Distance to water', 'Forest cover', 'Human disturbance', 'Elevation', 'Prey density']))
  }

  const recommendations: string[] = []
  recommendations.push('Add ' + randInt(rng, 5, 20) + ' camera stations to cover spatial gaps')
  recommendations.push('Extend deployment by ' + randInt(rng, 30, 90) + ' days for rare species documentation')
  recommendations.push('Repair/replace ' + malfunctionStations.length + ' malfunctioning stations')
  recommendations.push('Focus on ' + lowDetection.length + ' low-detection species for targeted surveys')
  recommendations.push('Implement AI-powered real-time species classification for ' + totalImages + ' images')
  recommendations.push('Standardize camera height/angle across all ' + input.num_cameras + ' stations')

  return {
    analysis_id: analysisId,
    deployment_region: input.deployment_region,
    total_images_captured: totalImages,
    total_species_detected: detections.length,
    trap_nights: trapNights,
    detections,
    stations,
    species_richness_estimate: speciesRichnessEstimate,
    rarefaction_curve: rarefactionCurve,
    detection_gaps: detectionGaps,
    occupancy_results: occupancyResults,
    recommendations,
  }
}

