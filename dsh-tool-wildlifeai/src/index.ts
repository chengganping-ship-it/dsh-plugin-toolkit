function runSpeciesMonitoring(input: SpeciesMonitoringInput): SpeciesMonitoringResult {
  const rng = createRngFromInput(input)
  const monitoringId = 'SM-' + randInt(rng, 10000, 99999)

  const iucnStatuses = ['Critical', 'Endangered', 'Vulnerable', 'Near Threatened', 'Least Concern']
  const habitats = ['Tropical Rainforest', 'Savanna', 'Wetland', 'Grassland', 'Montane Forest', 'Mangrove', 'Coral Reef', 'Desert', 'Temperate Forest', 'Arctic Tundra']
  const threats = ['Habitat Loss', 'Poaching', 'Climate Change', 'Invasive Species', 'Pollution', 'Human-Wildlife Conflict', 'Disease', 'Deforestation', 'Mining', 'Agricultural Expansion']
  const trends: SpeciesObservation['trend'][] = ['increasing', 'stable', 'declining', 'unknown']

  const speciesPool = input.target_species.length > 0 ? input.target_species : [
    'African Elephant', 'Mountain Gorilla', 'Snow Leopard', 'Bengal Tiger', 'Giant Panda',
    'Blue Whale', 'Orangutan', 'Black Rhino', 'Amur Leopard', 'Hawksbill Sea Turtle',
    'Sumatran Elephant', 'Saola', 'Vaquita', 'Javan Rhino', 'Cross River Gorilla'
  ]

  const observationCount = randInt(rng, Math.min(5, speciesPool.length), Math.min(15, speciesPool.length))
  const selectedSpecies = pickN(rng, speciesPool, observationCount)
  const observations: SpeciesObservation[] = []

  for (const sp of selectedSpecies) {
    const trend = pick(rng, trends)
    const trendPercent = trend === 'increasing' ? randFloat(rng, 0.5, 8.0) :
                         trend === 'declining' ? -randFloat(rng, 0.5, 12.0) :
                         trend === 'stable' ? randFloat(rng, -0.3, 0.3) : 0
    const popEstimate = randInt(rng, 10, 50000)
    const ciLow = Math.round(popEstimate * (0.75 + rng() * 0.1))
    const ciHigh = Math.round(popEstimate * (1.1 + rng() * 0.25))

    observations.push({
      species_name: sp,
      scientific_name: 'SP-' + randInt(rng, 1000, 9999) + ' ' + pick(rng, ['africana', 'tigris', 'uncia', 'beringianus', 'giganteus', 'pygmaeus']),
      iucn_status: pick(rng, iucnStatuses),
      population_estimate: popEstimate,
      confidence_interval: [ciLow, ciHigh],
      trend,
      trend_percent_annual: trendPercent,
      last_observed: '2025-' + String(randInt(rng, 1, 12)).padStart(2, '0') + '-' + String(randInt(rng, 1, 28)).padStart(2, '0'),
      habitat_type: pick(rng, habitats),
      threats: pickN(rng, threats, randInt(rng, 1, 4)),
    })
  }

  // Filter by threat level
  let filteredObservations = observations
  const threatRank: Record<string, number> = { 'Least Concern': 0, 'Near Threatened': 1, 'Vulnerable': 2, 'Endangered': 3, 'Critical': 4 }
  if (input.threat_level_filter !== 'all') {
    const filterRank = threatRank[input.threat_level_filter.charAt(0).toUpperCase() + input.threat_level_filter.slice(1)]
    filteredObservations = observations.filter(o => (threatRank[o.iucn_status] || 0) <= filterRank)
  }

  const populationTrends: string[] = []
  if (input.include_population_trend) {
    const declining = filteredObservations.filter(o => o.trend === 'declining')
    const increasing = filteredObservations.filter(o => o.trend === 'increasing')
    populationTrends.push(declining.length + ' species showing declining populations in ' + input.region)
    populationTrends.push(increasing.length + ' species showing population recovery/growth')
    if (declining.length > 0) {
      populationTrends.push('Most threatened: ' + declining[0].species_name + ' (' + declining[0].trend_percent_annual.toFixed(1) + '% annual decline)')
    }
    populationTrends.push('Overall ecosystem stability index: ' + (randFloat(rng, 0.4, 0.9) * 100).toFixed(0) + '%')
  }

  const conservationPriorities: string[] = []
  const criticalSpecies = filteredObservations.filter(o => o.iucn_status === 'Critical' || o.iucn_status === 'Endangered')
  for (const sp of criticalSpecies.slice(0, 3)) {
    conservationPriorities.push(sp.species_name + ' (' + sp.iucn_status + ') - Pop: ' + sp.population_estimate + ' - Immediate action required')
  }
  if (filteredObservations.length > 0) {
    const habitatLoss = filteredObservations.filter(o => o.threats.includes('Habitat Loss')).length
    if (habitatLoss > 0) conservationPriorities.push('Habitat protection needed for ' + habitatLoss + ' species facing habitat loss')
  }

  const alertFlags: string[] = []
  for (const obs of filteredObservations) {
    if (obs.trend === 'declining' && obs.trend_percent_annual < -5) {
      alertFlags.push('RAPID DECLINE: ' + obs.species_name + ' declining at ' + Math.abs(obs.trend_percent_annual).toFixed(1) + '%/year')
    }
    if (obs.population_estimate < 500) {
      alertFlags.push('CRITICALLY LOW: ' + obs.species_name + ' estimated below 500 individuals')
    }
  }

  const recommendations: string[] = []
  recommendations.push('Increase monitoring frequency for ' + criticalSpecies.length + ' at-risk species surveyed')
  recommendations.push('Deploy additional ' + input.survey_method + ' units across ' + input.region)
  recommendations.push('Establish anti-poaching patrols in high-threat zones')
  recommendations.push('Implement habitat corridor restoration between fragmented zones')
  recommendations.push('Conduct community engagement programs to reduce human-wildlife conflict')

  return {
    monitoring_id: monitoringId,
    region: input.region,
    duration_months: input.monitoring_duration_months,
    survey_method: input.survey_method,
    total_species_detected: filteredObservations.length,
    observations: filteredObservations,
    population_trends: populationTrends,
    conservation_priorities: conservationPriorities,
    alert_flags: alertFlags,
    recommendations,
  }
}

function formatSpeciesMonitoringReport(r: SpeciesMonitoringResult): string {
  const lines: string[] = []
  lines.push('## Species Monitoring Report')
  lines.push('')
  lines.push('**Monitoring ID:** ' + r.monitoring_id + ' | **Region:** ' + r.region + ' | **Duration:** ' + r.duration_months + ' months')
  lines.push('**Survey Method:** ' + r.survey_method + ' | **Species Detected:** ' + r.total_species_detected)
  lines.push('')
  lines.push('### Species Observations')
  lines.push('| Species | IUCN Status | Population | Trend | Annual % | Habitat |')
  lines.push('|---------|-------------|------------|-------|----------|---------|')
  for (const o of r.observations) {
    lines.push('| ' + o.species_name + ' | ' + o.iucn_status + ' | ' + o.population_estimate + ' | ' + o.trend + ' | ' + (o.trend_percent_annual >= 0 ? '+' : '') + o.trend_percent_annual.toFixed(1) + '% | ' + o.habitat_type + ' |')
  }
  lines.push('')
  lines.push('### Threats Summary')
  for (const o of r.observations) {
    lines.push('- **' + o.species_name + ':** ' + o.threats.join(', '))
  }
  lines.push('')
  if (r.population_trends.length > 0) {
    lines.push('### Population Trends')
    for (const t of r.population_trends) lines.push('- ' + t)
    lines.push('')
  }
  if (r.alert_flags.length > 0) {
    lines.push('## Alert Flags')
    for (const a of r.alert_flags) lines.push('- **' + a + '**')
    lines.push('')
  }
  lines.push('### Conservation Priorities')
  for (const p of r.conservation_priorities) lines.push('- **[PRIORITY]** ' + p)
  lines.push('')
  lines.push('### Recommendations')
  for (const rec of r.recommendations) lines.push('- [ ] ' + rec)
  lines.push('')
  lines.push('> **Disclaimer:** ' + DISCLAIMER)
  return lines.join('\n')
}

