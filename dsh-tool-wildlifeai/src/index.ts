function trackMigration(input: MigrationTrackerInput): MigrationTrackerResult {
  const rng = createRngFromInput(input)
  const trackerId = 'MT-' + randInt(rng, 10000, 99999)

  const routeCount = randInt(rng, 1, Math.min(5, input.num_tracked_individuals))
  const routes: MigrationRoute[] = []

  for (let i = 0; i < routeCount; i++) {
    const waypointCount = randInt(rng, 3, 10)
    const waypoints: MigrationWaypoint[] = []

    for (let j = 0; j < waypointCount; j++) {
      const arrivalMonth = randInt(rng, 1, 12)
      const duration = randInt(rng, 1, 45)
      waypoints.push({
        site_id: 'S' + String(j + 1).padStart(3, '0'),
        name: pick(rng, ['Wetland Reserve', 'Coastal Bay', 'Mountain Pass', 'River Delta', 'Grassland Plain', 'Forest Edge', 'Lake Shore', 'Estuary', 'Island Stopover', 'Agricultural Field']),
        coordinates: [randFloat(rng, -180, 180), randFloat(rng, -90, 90)],
        arrival_date: '2025-' + String(arrivalMonth).padStart(2, '0') + '-' + String(randInt(rng, 1, 28)).padStart(2, '0'),
        departure_date: '2025-' + String(Math.min(12, arrivalMonth + Math.ceil(duration / 30))).padStart(2, '0') + '-' + String(randInt(rng, 1, 28)).padStart(2, '0'),
        duration_days: duration,
        habitat_type: pick(rng, ['Wetland', 'Grassland', 'Coastal', 'Forest', 'Agricultural', 'Freshwater', 'Marine']),
        threat_level: pick(rng, ['Low', 'Medium', 'High', 'Critical'] as const),
        protection_status: pick(rng, ['Protected', 'Partial', 'Unprotected', 'Protected', 'Partial']),
      })
    }

    routes.push({
      route_id: 'R' + String(i + 1).padStart(3, '0'),
      start_location: pick(rng, ['Breeding Ground A', 'Northern Range', 'Summer Habitat', 'Arctic Tundra', 'Highland Plateau']),
      end_location: pick(rng, ['Wintering Ground B', 'Southern Range', 'Winter Habitat', 'Tropical Lowland', 'Coastal Wetland']),
      total_distance_km: randInt(rng, 500, 20000),
      duration_days: randInt(rng, 14, 180),
      max_altitude_m: randInt(rng, 500, 9000),
      waypoints,
      barriers_encountered: pickN(rng, ['Major Highway', 'Wind Farm', 'Urban Area', 'Dam', 'Fence Line', 'Agricultural Expansion', 'Power Lines', 'Industrial Zone'], randInt(rng, 1, 4)),
      climate_vulnerability: pick(rng, ['Low', 'Medium', 'High'] as const),
    })
  }

  const stopoverAnalysis: string[] = []
  if (input.include_stopover_sites) {
    const allWaypoints = routes.flatMap(r => r.waypoints)
    const criticalStopovers = allWaypoints.filter(w => w.threat_level === 'Critical' || w.threat_level === 'High')
    stopoverAnalysis.push('Total stopover sites identified: ' + allWaypoints.length + ' across ' + routes.length + ' routes')
    stopoverAnalysis.push('Critical/High threat stopovers: ' + criticalStopovers.length + ' requiring immediate protection')
    stopoverAnalysis.push('Average stopover duration: ' + Math.round(allWaypoints.reduce((s, w) => s + w.duration_days, 0) / allWaypoints.length) + ' days')
    const unprotected = allWaypoints.filter(w => w.protection_status === 'Unprotected')
    if (unprotected.length > 0) {
      stopoverAnalysis.push('UNPROTECTED stopovers: ' + unprotected.length + ' sites need protection status urgently')
    }
  }

  const timingAnalysis: string[] = []
  timingAnalysis.push('Tracking duration: ' + input.study_duration_months + ' months with ' + input.num_tracked_individuals + ' individuals')
  timingAnalysis.push('Peak migration period: ' + pick(rng, ['March-April', 'September-October', 'November-December', 'January-February']))
  timingAnalysis.push('Average migration speed: ' + randInt(rng, 30, 200) + ' km/day')
  timingAnalysis.push('Nocturnal migration proportion: ' + randInt(rng, 40, 90) + '%')
  if (input.climate_scenario !== 'current') {
    timingAnalysis.push('Phenological shift under ' + input.climate_scenario + ': ' + randInt(rng, 5, 25) + ' days earlier arrival')
  }

  const threatsAlongRoute: string[] = []
  const allBarriers = routes.flatMap(r => r.barriers_encountered)
  const barrierCounts: Record<string, number> = {}
  for (const b of allBarriers) barrierCounts[b] = (barrierCounts[b] || 0) + 1
  for (const [barrier, count] of Object.entries(barrierCounts)) {
    threatsAlongRoute.push(barrier + ': encountered on ' + count + ' routes')
  }
  threatsAlongRoute.push('Habitat loss at stopover sites: ' + randInt(rng, 10, 40) + '% reduction over past decade')
  threatsAlongRoute.push('Hunting pressure at ' + randInt(rng, 1, 5) + ' stopover locations')
  threatsAlongRoute.push('Light pollution disrupting nocturnal migration at ' + randInt(rng, 2, 8) + ' sites')

  const corridorRecommendations: string[] = []
  corridorRecommendations.push('Establish ' + routes.length + ' formal migration corridors with international protection')
  corridorRecommendations.push('Protect ' + randInt(rng, 3, 12) + ' critical stopover sites along primary routes')
  corridorRecommendations.push('Install wildlife crossings at ' + (barrierCounts['Major Highway'] || 0) + ' highway barrier points')
  corridorRecommendations.push('Create buffer zones of ' + randInt(rng, 1, 5) + ' km around key stopover wetlands')
  corridorRecommendations.push('Coordinate international conservation agreements across ' + randInt(rng, 2, 8) + ' range states')

  const climateImpactAssessment: string[] = []
  if (input.climate_scenario === 'warming_1.5C') {
    climateImpactAssessment.push('1.5C scenario: ' + randInt(rng, 5, 15) + '% shift in breeding range expected')
    climateImpactAssessment.push('Stopover site suitability: ' + randInt(rng, 80, 95) + '% maintained')
  } else if (input.climate_scenario === 'warming_2C') {
    climateImpactAssessment.push('2C scenario: ' + randInt(rng, 15, 30) + '% shift in breeding range expected')
    climateImpactAssessment.push('Stopover site suitability: ' + randInt(rng, 60, 80) + '% maintained')
    climateImpactAssessment.push('Phenological mismatch risk: Moderate to High')
  } else if (input.climate_scenario === 'warming_3C') {
    climateImpactAssessment.push('3C scenario: ' + randInt(rng, 30, 60) + '% shift in breeding range expected')
    climateImpactAssessment.push('Stopover site suitability: ' + randInt(rng, 30, 60) + '% maintained')
    climateImpactAssessment.push('Phenological mismatch risk: Severe - food availability timing disrupted')
  } else {
    climateImpactAssessment.push('Current climate: Migration timing and routes within historical norms')
  }
  climateImpactAssessment.push('Sea level rise impact on coastal stopovers: ' + randInt(rng, 5, 25) + '% habitat loss')

  const populationConnectivity: string[] = []
  populationConnectivity.push('Tracked individuals represent ' + randInt(rng, 1, 15) + '% of estimated source population')
  populationConnectivity.push('Route fidelity: ' + randInt(rng, 60, 95) + '% of individuals return to same sites')
  populationConnectivity.push('Genetic exchange between populations: ' + pick(rng, ['High', 'Moderate', 'Low']))
  populationConnectivity.push('Meta-population structure: ' + randInt(rng, 2, 6) + ' subpopulations connected by migration')
  populationConnectivity.push('Isolation risk: ' + (routes.length > 2 ? 'Low - multiple routes provide redundancy' : 'High - limited route diversity'))

  return {
    tracker_id: trackerId,
    species: input.species,
    tracking_method: input.tracking_method,
    routes,
    stopover_analysis: stopoverAnalysis,
    timing_analysis: timingAnalysis,
    threats_along_route: threatsAlongRoute,
    corridor_recommendations: corridorRecommendations,
    climate_impact_assessment: climateImpactAssessment,
    population_connectivity: populationConnectivity,
  }
}

