  const lines: string[] = []
  const ipName = input.original_ip?.name || 'IP'

  lines.push('## Derivative Works Strategy')
  lines.push('')
  lines.push(`**${ipName}** | Genre: ${input.original_ip?.genre || 'N/A'} | Target Audiences: ${input.original_ip?.audience || 'N/A'}`)
