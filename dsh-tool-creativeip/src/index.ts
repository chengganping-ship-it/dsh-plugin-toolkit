interface AntiPiracyInput {
  content_type: string
  distribution_channels: string[]
  monitoring_budget_usd: number
  takedown_speed_requirement: 'standard' | 'fast' | 'immediate'
  jurisdiction: string[]
}

interface MonitoringLayer {
  layer: string
  technique: string
  coverage_pct: number
  cost_usd: number
  response_time: string
  effectiveness: 'high' | 'medium' | 'low'
}

interface AntiPiracyResult {
  monitoring_layers: MonitoringLayer[]
  total_coverage: number
  total_cost: number
  takedown_avg_hours: number
  prevention_tips: string[]
  summary: string
}

function designAntiPiracyMonitoring(input: AntiPiracyInput): AntiPiracyResult {
  const rng = initRng(input)
  const channels = input.distribution_channels.length > 0 ? input.distribution_channels : ['web', 'social_media', 'torrent']
  const budget = input.monitoring_budget_usd || 2000
  const speed = input.takedown_speed_requirement || 'standard'
  const contentType = input.content_type || 'digital_art'
  const jurisdictions = input.jurisdiction.length > 0 ? input.jurisdiction : ['US']

  const layers: MonitoringLayer[] = []

  // Web monitoring
  if (channels.includes('web') || channels.includes('website')) {
    layers.push({
      layer: 'Web Crawling & Detection',
      technique: 'Automated scraping + perceptual fingerprinting to detect unauthorized copies',
      coverage_pct: rngRange(rng, 60, 80),
      cost_usd: rngRange(rng, 500, 3000),
      response_time: speed === 'immediate' ? '2-6 hours' : speed === 'fast' ? '12-24 hours' : '24-72 hours',
      effectiveness: 'high',
    })
  }

  // Social media monitoring
  if (channels.includes('social_media') || channels.includes('platforms')) {
    layers.push({
      layer: 'Social Media Monitoring',
      technique: 'Platform API monitoring + image recognition for unauthorized reposts and edits',
      coverage_pct: rngRange(rng, 50, 75),
      cost_usd: rngRange(rng, 300, 2000),
      response_time: speed === 'immediate' ? '4-12 hours' : '24-48 hours',
      effectiveness: 'medium',
    })
  }

  // Torrent / P2P monitoring
  if (channels.includes('torrent') || channels.includes('p2p') || channels.includes('file_sharing')) {
    layers.push({
      layer: 'P2P/Torrent Monitoring',
      technique: 'Tracker monitoring + DHT scanning + swarm analysis for leaked content',
      coverage_pct: rngRange(rng, 40, 65),
      cost_usd: rngRange(rng, 500, 2500),
      response_time: speed === 'immediate' ? '6-12 hours' : '24-72 hours',
      effectiveness: 'medium',
    })
  }

  // Marketplace monitoring (prints, merch)
  if (channels.includes('marketplace') || channels.includes('prints') || channels.includes('merchandise')) {
    layers.push({
      layer: 'Marketplace Monitoring',
      technique: 'Automated product image matching on Etsy, Redbubble, Taobao, Amazon Merch',
      coverage_pct: rngRange(rng, 55, 70),
      cost_usd: rngRange(rng, 400, 2000),
      response_time: '24-72 hours',
      effectiveness: 'medium',
    })
  }

  // Watermarking / fingerprinting (preventive)
  layers.push({
    layer: 'Digital Watermarking',
    technique: 'Invisible forensic watermarking embedded in original files for leak source tracing',
    coverage_pct: rngRange(rng, 80, 95),
    cost_usd: rngRange(rng, 200, 1500),
    response_time: 'N/A (preventive)',
    effectiveness: 'high',
  })

  // Fallback if no channels matched
  if (layers.length === 0) {
    layers.push({
      layer: 'Basic Web Monitoring',
      technique: 'Automated reverse image search and keyword monitoring',
      coverage_pct: rngRange(rng, 40, 60),
      cost_usd: rngRange(rng, 200, 1000),
      response_time: '48-72 hours',
      effectiveness: 'medium',
    })
  }

  const totalCoverage = Math.min(95, Math.round(layers.reduce((s, l) => s + l.coverage_pct, 0) / layers.length + rngRange(rng, 5, 15)))
  const totalCost = layers.reduce((s, l) => s + l.cost_usd, 0)

  const avgHours = speed === 'immediate' ? rngRange(rng, 4, 12) : speed === 'fast' ? rngRange(rng, 12, 36) : rngRange(rng, 24, 72)

  const preventionTips: string[] = [
    'Register copyright in all target jurisdictions before content launch — enables statutory damages',
    'Use visible watermarks on preview/low-res versions; invisible forensic watermarks on full-res',
    'Implement DMCA-compliant takedown process with pre-prepared templates for each platform',
    'Monitor newly registered domain names containing your IP names — early indicator of piracy ecosystems',
    'Release content strategically: staggered regional releases reduce mass piracy incentives',
    'Build fan community — loyal fans actively report piracy and support official channels',
    'Consider blockchain/NFT provenance for high-value digital artworks',
    'Partner with anti-piracy service providers (Mintz, MarkMonitor, Red Points) for enterprise-grade monitoring',
  ]

  return {
    monitoring_layers: layers,
    total_coverage: totalCoverage,
    total_cost: totalCost,
    takedown_avg_hours: avgHours,
    prevention_tips: preventionTips,
    summary: `${contentType} | ${layers.length} monitoring layers | ${totalCoverage}% coverage | $${totalCost.toLocaleString()} cost | Avg takedown: ${avgHours}h | ${jurisdictions.length} jurisdiction(s)`,
  }
}

