// ==================== TOOL 1: IP REGISTRATION ADVISOR ====================

interface IPRRegistrationInput {
  work_type: string
  jurisdiction: string[]
  budget_usd: number
  commercial_potential: 'low' | 'medium' | 'high' | 'blockbuster'
  prior_art_search_needed: boolean
}

interface IPRegistrationAction {
  type: string
  estimated_cost_usd: number
  timeline_months: number
  priority: 'critical' | 'high' | 'medium' | 'low'
  notes: string
}

interface IPRegistrationResult {
  registration_strategy: string
  actions: IPRegistrationAction[]
  total_estimated_cost: number
  risk_level: string
  timeline_months: number
  summary: string
}

function adviseIPRegistration(input: IPRRegistrationInput): IPRegistrationResult {
  const rng = initRng(input)
  const jurisdictions = input.jurisdiction.length > 0 ? input.jurisdiction : ['US']
  const commercial = input.commercial_potential || 'medium'
  const budget = input.budget_usd || 5000
  const workType = input.work_type || 'digital_art'

  const actions: IPRegistrationAction[] = []

  // Copyright registration
  const copyrightBaseCost = jurisdictions.length * rngRange(rng, 35, 65)
  actions.push({
    type: 'Copyright Registration',
    estimated_cost_usd: copyrightBaseCost,
    timeline_months: rngRange(rng, 3, 8),
    priority: 'critical',
    notes: 'Automatic upon creation, but registration required for statutory damages in US. File in each target jurisdiction.',
  })

  // Trademark (if commercial potential is medium+)
  if (commercial !== 'low') {
    const tmCost = jurisdictions.length * rngRange(rng, 1000, 2500)
    actions.push({
      type: 'Trademark Registration (Name/Logo)',
      estimated_cost_usd: tmCost,
      timeline_months: rngRange(rng, 8, 18),
      priority: commercial === 'high' || commercial === 'blockbuster' ? 'critical' : 'high',
      notes: `Protects brand identity across ${jurisdictions.length} jurisdiction(s). Essential for merchandising and franchise value. Madrid Protocol can reduce multi-country costs by 40-60%.`,
    })
  }

  // Patent (only for certain work types)
  if (workType === 'game_mechanics' || workType === 'software' || workType === 'interactive_system') {
    const patentCost = rngRange(rng, 8000, 15000)
    if (budget > patentCost * 0.5) {
      actions.push({
        type: 'Utility/Design Patent',
        estimated_cost_usd: patentCost,
        timeline_months: rngRange(rng, 18, 36),
        priority: 'medium',
        notes: 'Consider provisional patent first ($2,000-3,500) to secure priority date. Full patent is expensive — evaluate ROI based on product lifecycle.',
      })
    }
  }

  // Prior art search
  if (input.prior_art_search_needed) {
    actions.push({
      type: 'Prior Art Search',
      estimated_cost_usd: rngRange(rng, 1500, 5000),
      timeline_months: rngRange(rng, 1, 3),
      priority: 'high',
      notes: 'Essential before full IP investment. Identifies potential infringement risks and strengthens application quality.',
    })
  }

  // International strategy
  if (jurisdictions.length > 1) {
    actions.push({
      type: 'International IP Filing Strategy',
      estimated_cost_usd: rngRange(rng, 2000, 8000),
      timeline_months: rngRange(rng, 6, 24),
      priority: 'high',
      notes: 'PCT Patent, Madrid Protocol Trademark, Berne Convention Copyright (automatic in 180+ countries). Budget for translation and local counsel fees.',
    })
  }

  // Monitoring / enforcement setup
  actions.push({
    type: 'IP Monitoring Setup',
    estimated_cost_usd: rngRange(rng, 500, 3000),
    timeline_months: rngRange(rng, 1, 2),
    priority: 'medium',
    notes: 'Set up watch services for trademark, copyright infringement monitoring, and domain name monitoring.',
  })

  // Sort by priority
  const priorityOrder = { critical: 0, high: 1, medium: 2, low: 3 }
  actions.sort((a, b) => priorityOrder[a.priority] - priorityOrder[b.priority])

  const totalCost = actions.reduce((s, a) => s + a.estimated_cost_usd, 0)
  const maxTimeline = Math.max(...actions.map(a => a.timeline_months))

  let riskLevel = 'low'
  if (actions.some(a => a.priority === 'critical' && a.estimated_cost_usd > budget * 0.4)) riskLevel = 'medium'
  if (totalCost > budget * 1.5) riskLevel = 'high'

  let strategy = 'Phased Registration'
  if (budget > totalCost * 1.2) strategy = 'Full-Stack IP Protection'
  else if (budget < totalCost * 0.5) strategy = 'Essential-Only Protection'

  return {
    registration_strategy: strategy,
    actions,
    total_estimated_cost: totalCost,
    risk_level: riskLevel,
    timeline_months: maxTimeline,
    summary: `Strategy: ${strategy} | Total estimated cost: $${totalCost.toLocaleString()} across ${actions.length} actions | Budget: $${budget.toLocaleString()} | Risk: ${riskLevel} | ${jurisdictions.length} jurisdiction(s)`,
  }
}

function formatIPRegistrationReport(input: IPRRegistrationInput, result: IPRegistrationResult): string {
  const lines: string[] = []

  lines.push('## IP Registration Strategy')
  lines.push('')
  lines.push(`**${input.work_type || 'Creative Work'}** | Jurisdictions: ${input.jurisdiction.join(', ') || 'US'} | Budget: $${(input.budget_usd || 0).toLocaleString()}`)
  lines.push('')
  lines.push(result.summary)
  lines.push('')

  lines.push('### Recommended Actions')
  lines.push('| # | Action | Cost (USD) | Timeline | Priority | Notes |')
  lines.push('|---|--------|------------|----------|----------|-------|')
  let idx = 1
  for (const a of result.actions) {
    const priTag = a.priority.toUpperCase()
    lines.push(`| ${idx} | ${a.type} | $${a.estimated_cost_usd.toLocaleString()} | ${a.timeline_months}mo | ${priTag} | ${a.notes} |`)
    idx++
  }
  lines.push('')

  lines.push(`### Budget Analysis`)
  lines.push(`- **Estimated Total**: $${result.total_estimated_cost.toLocaleString()}`)
  lines.push(`- **Available Budget**: $${(input.budget_usd || 0).toLocaleString()}`)
  const coverage = input.budget_usd > 0 ? Math.min(100, Math.round((input.budget_usd / result.total_estimated_cost) * 100)) : 0
  lines.push(`- **Budget Coverage**: ${coverage}%`)
  lines.push(`- **Risk Level**: ${result.risk_level.toUpperCase()}`)
  lines.push('')

  lines.push('### Commercial Potential Context')
  lines.push(`- **Level**: ${input.commercial_potential || 'medium'}`)
  lines.push(`- **Recommendation**: ${result.registration_strategy}`)
  lines.push('')

  lines.push(DISCLAIMER)
  return lines.join('\n')
}

// ==================== TOOL 2: DERIVATIVE WORKS STRATEGIST ====================

interface DerivativeWorksInput {
  original_ip: { name: string; genre: string; audience: string }
  target_formats: string[]
  market_demand: { format: string; demand_score: number }[]
  budget_usd: number
  timeline_months: number
}

interface DerivativePlan {
  format: string
  priority: 'must_do' | 'high' | 'medium' | 'low'
  estimated_revenue_usd: number
  estimated_cost_usd: number
  timeline_months: number
  notes: string
}

interface DerivativeWorksResult {
  total_revenue_potential: number
  total_investment: number
  plans: DerivativePlan[]
  roadmap: string[]
  summary: string
}

function planDerivativeWorks(input: DerivativeWorksInput): DerivativeWorksResult {
  const rng = initRng(input)
  const formats = input.target_formats.length > 0 ? input.target_formats : ['merchandise', 'digital_content']
  const budget = input.budget_usd || 10000
  const timeline = input.timeline_months || 12
  const ipName = input.original_ip?.name || 'IP'

  const allFormatPools: Record<string, { costRange: [number, number]; revenueMult: number; speed: string }> = {
    merchandise: { costRange: [2000, 15000], revenueMult: 1.5, speed: 'fast' },
    graphic_novel: { costRange: [5000, 40000], revenueMult: 2.0, speed: 'medium' },
    animated_series: { costRange: [20000, 500000], revenueMult: 5.0, speed: 'slow' },
    video_game: { costRange: [10000, 200000], revenueMult: 3.5, speed: 'slow' },
    live_action: { costRange: [50000, 5000000], revenueMult: 8.0, speed: 'very_slow' },
    mobile_app: { costRange: [3000, 50000], revenueMult: 2.5, speed: 'medium' },
    digital_collectible: { costRange: [1000, 20000], revenueMult: 1.8, speed: 'fast' },
    fiction_novel: { costRange: [2000, 25000], revenueMult: 1.5, speed: 'medium' },
    soundtrack_album: { costRange: [3000, 30000], revenueMult: 1.3, speed: 'medium' },
    vr_experience: { costRange: [15000, 300000], revenueMult: 2.0, speed: 'slow' },
  }

  const plans: DerivativePlan[] = []
  for (const format of formats) {
    const pool = allFormatPools[format] || { costRange: [2000, 15000], revenueMult: 1.5, speed: 'medium' }
    const demand = input.market_demand?.find(m => m.format === format)?.demand_score || rngRange(rng, 40, 85)
    const cost = rngRange(rng, pool.costRange[0], pool.costRange[1])
    const revenue = Math.round(cost * pool.revenueMult * (demand / 70) * (0.8 + rng() * 0.4))

    let priority: DerivativePlan['priority'] = 'medium'
    if (demand >= 80 && pool.speed === 'fast') priority = 'must_do'
    else if (demand >= 65) priority = 'high'
    else if (demand < 45) priority = 'low'

    const speedMonths = pool.speed === 'fast' ? rngRange(rng, 1, 3) : pool.speed === 'medium' ? rngRange(rng, 3, 8) : pool.speed === 'slow' ? rngRange(rng, 6, 18) : rngRange(rng, 12, 36)

    plans.push({
      format,
      priority,
      estimated_revenue_usd: revenue,
      estimated_cost_usd: cost,
      timeline_months: clamp(speedMonths, 1, timeline),
      notes: `Demand score: ${demand}/100 | Speed: ${pool.speed} | Expected revenue multiplier: ${pool.revenueMult}x`,
    })
  }

  // Sort by priority
  const priorityOrder = { must_do: 0, high: 1, medium: 2, low: 3 }
  plans.sort((a, b) => priorityOrder[a.priority] - priorityOrder[b.priority])

  const totalRevenue = plans.reduce((s, p) => s + p.estimated_revenue_usd, 0)
  const totalInvestment = plans.reduce((s, p) => s + p.estimated_cost_usd, 0)

  const roadmap: string[] = []
  const mustDo = plans.filter(p => p.priority === 'must_do')
  const high = plans.filter(p => p.priority === 'high')

  if (mustDo.length > 0) roadmap.push(`Phase 1 (0-3 months): Launch ${mustDo.map(p => p.format).join(', ')} — high-demand fast formats`)
  if (high.length > 0) roadmap.push(`Phase 2 (3-${Math.min(12, timeline)} months): Develop ${high.map(p => p.format).join(', ')} — expand audience reach`)
  roadmap.push(`Phase 3 (${Math.min(12, timeline)}+ months): Evaluate remaining formats based on Phase 1-2 performance data`)
  roadmap.push('Cross-promote all formats: each derivative drives traffic to the original and other products')

  return {
    total_revenue_potential: totalRevenue,
    total_investment: totalInvestment,
    plans,
    roadmap,
    summary: `${ipName} | ${plans.length} derivative format(s) planned | Revenue potential: $${totalRevenue.toLocaleString()} | Investment: $${totalInvestment.toLocaleString()} | ROI ratio: ${totalInvestment > 0 ? (totalRevenue / totalInvestment).toFixed(1) : 0}x`,
  }
}

