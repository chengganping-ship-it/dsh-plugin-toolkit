interface LicensingInput {
  ip_assets: { asset_name: string; asset_type: string }[]
  licensee_profile: { company: string; size: string; territory: string }
  deal_type: 'exclusive' | 'non_exclusive' | 'sole'
  minimum_guarantee_usd: number
  royalty_rate_range: { min_pct: number; max_pct: number }
}

interface LicensingDealResult {
  deal_terms: {
    territory: string
    duration_years: number
    exclusivity: string
    minimum_guarantee: number
    royalty_rate: string
    advance_usd: number
  }
  milestones: { milestone: string; payment_usd: number; deadline: string }[]
  risk_factors: string[]
  recommendations: string[]
  summary: string
}

function structureLicensingDeal(input: LicensingInput): LicensingDealResult {
  const rng = initRng(input)
  const mg = input.minimum_guarantee_usd || 10000
  const dealType = input.deal_type || 'non_exclusive'
  const territory = input.licensee_profile?.territory || 'Global'
  const company = input.licensee_profile?.company || 'Licensee'
  const assets = input.ip_assets || []

  // Advance calculation
  const advanceMultiplier = dealType === 'exclusive' ? rngRange(rng, 10, 25) / 10 : rngRange(rng, 3, 8) / 10
  const advance = Math.round(mg * advanceMultiplier)

  // Duration
  const duration = dealType === 'exclusive' ? rngRange(rng, 3, 7) : rngRange(rng, 1, 3)

  // Royalty range
  const rateMin = input.royalty_rate_range?.min_pct || 5
  const rateMax = input.royalty_rate_range?.max_pct || 15
  const baseRate = rngRange(rng, rateMin, rateMax)

  // Milestones
  const milestones: LicensingDealResult['milestones'] = [
    {
      milestone: 'Signing / Advance Payment',
      payment_usd: advance,
      deadline: 'At contract execution',
    },
    {
      milestone: 'First Commercial Release',
      payment_usd: Math.round(mg * 0.25),
      deadline: `Within ${rngRange(rng, 6, 18)} months of signing`,
    },
    {
      milestone: 'Minimum Guarantee Achievement',
      payment_usd: mg,
      deadline: `${duration} years from signing`,
    },
    {
      milestone: 'Sales Target Bonus (if applicable)',
      payment_usd: Math.round(mg * 0.3),
      deadline: `Year ${Math.ceil(duration / 2)} of contract`,
    },
  ]

  const risks: string[] = []
  if (dealType === 'exclusive' && duration > 3) risks.push('Long exclusive deal may limit future licensing opportunities')
  if (mg < 5000) risks.push('Low minimum guarantee may not incentivize licensee commitment')
  if (assets.length > 5) risks.push('Licensing many assets in one deal increases compliance monitoring complexity')
  risks.push('Currency fluctuation risk if deal spans multi-year term across territories')
  risks.push('Licensee may not fully exploit the IP — include performance clauses with reversal rights')

  const recommendations: string[] = []
  recommendations.push(`Structure royalty at ${baseRate}% of net revenue (standard for ${assets[0]?.asset_type || 'creative content'})`)
  if (dealType === 'exclusive') {
    recommendations.push('Exclusive deal: require minimum annual performance or territory reverts to licensor')
    recommendations.push('Include quarterly reporting and audit rights to verify royalty calculations')
  }
  recommendations.push('Define "Net Revenue" explicitly in contract — exclude only documented platform fees and returns')
  recommendations.push('Include clause for sublicensing approval to prevent unauthorized third-party licensing')
  recommendations.push('Add IP protection clause: licensee must maintain quality standards and brand guidelines')
  recommendations.push('Consider escalation clause: royalty rate increases after revenue milestones')
  if (duration > 3) recommendations.push('Long-term deal: include termination option at year 2-3 with buy-back clause')

  return {
    deal_terms: {
      territory,
      duration_years: duration,
      exclusivity: dealType,
      minimum_guarantee: mg,
      royalty_rate: `${rateMin}%-${rateMax}% (recommended: ${baseRate}%)`,
      advance_usd: advance,
    },
    milestones,
    risk_factors: risks,
    recommendations,
    summary: `${company} | ${dealType} license | ${territory} | ${duration}yr term | MG: $${mg.toLocaleString()} | Advance: $${advance.toLocaleString()} | Royalty: ${rateMin}%-${rateMax}%`,
  }
}

