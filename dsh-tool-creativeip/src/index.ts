interface CrossMediaInput {
  source_ip: { title: string; medium: string }
  target_media: string[]
  audience_analysis: { primary_age: string; platforms: string[] }
  production_budget_usd: number
  risk_tolerance: 'low' | 'medium' | 'high'
}

interface AdaptationStep {
  from_medium: string
  to_medium: string
  difficulty: 'straightforward' | 'moderate' | 'complex' | 'very_complex'
  estimated_cost_usd: number
  estimated_timeline_months: number
  key_challenges: string[]
  opportunities: string[]
}

interface CrossMediaResult {
  adaptation_path: AdaptationStep[]
  total_cost: number
  total_timeline: number
  risk_assessment: string
  summary: string
}

function planCrossMediaAdaptation(input: CrossMediaInput): CrossMediaResult {
  const rng = initRng(input)
  const targets = input.target_media.length > 0 ? input.target_media : ['animation', 'game']
  const budget = input.production_budget_usd || 50000
  const source = input.source_ip?.medium || 'novel'
  const risk = input.risk_tolerance || 'medium'
  const ipTitle = input.source_ip?.title || 'IP'

  const adaptationMatrix: Record<string, { difficulty: AdaptationStep['difficulty']; costMult: [number, number]; timeRange: [number, number] }> = {
    'novel_to_animation': { difficulty: 'complex', costMult: [10000, 100000], timeRange: [6, 24] },
    'novel_to_game': { difficulty: 'complex', costMult: [5000, 80000], timeRange: [4, 18] },
    'novel_to_film': { difficulty: 'very_complex', costMult: [50000, 5000000], timeRange: [12, 36] },
    'novel_to_comic': { difficulty: 'moderate', costMult: [2000, 30000], timeRange: [3, 12] },
    'game_to_animation': { difficulty: 'complex', costMult: [20000, 300000], timeRange: [6, 18] },
    'game_to_film': { difficulty: 'very_complex', costMult: [50000, 5000000], timeRange: [12, 36] },
    'game_to_novel': { difficulty: 'straightforward', costMult: [1000, 15000], timeRange: [3, 8] },
    'game_to_comic': { difficulty: 'moderate', costMult: [2000, 25000], timeRange: [3, 10] },
    'animation_to_game': { difficulty: 'complex', costMult: [5000, 100000], timeRange: [4, 18] },
    'animation_to_novel': { difficulty: 'straightforward', costMult: [1000, 12000], timeRange: [3, 8] },
    'animation_to_film': { difficulty: 'very_complex', costMult: [50000, 5000000], timeRange: [12, 36] },
    'comic_to_animation': { difficulty: 'moderate', costMult: [10000, 200000], timeRange: [6, 18] },
    'comic_to_game': { difficulty: 'complex', costMult: [5000, 80000], timeRange: [4, 16] },
    'comic_to_film': { difficulty: 'very_complex', costMult: [50000, 5000000], timeRange: [12, 36] },
    'animation_to_comic': { difficulty: 'moderate', costMult: [2000, 20000], timeRange: [3, 10] },
    'game_to_merchandise': { difficulty: 'straightforward', costMult: [1000, 20000], timeRange: [2, 6] },
    'novel_to_merchandise': { difficulty: 'straightforward', costMult: [500, 15000], timeRange: [2, 5] },
    'animation_to_merchandise': { difficulty: 'straightforward', costMult: [1000, 25000], timeRange: [2, 6] },
  }

  const adaptationPath: AdaptationStep[] = []

  for (const target of targets) {
    const key = `${source}_to_${target}`
    const matrix = adaptationMatrix[key] || {
      difficulty: 'moderate' as AdaptationStep['difficulty'],
      costMult: [2000, 30000] as [number, number],
      timeRange: [3, 12] as [number, number],
    }

    const costCostMult: [number, number] = matrix.costMult
    const cost = rngRange(rng, costCostMult[0], costCostMult[1])
    const time = rngRange(rng, matrix.timeRange[0], matrix.timeRange[1])

    const challenges: string[] = []
    const opportunities: string[] = []

    if (matrix.difficulty === 'very_complex') {
      challenges.push('Requires significant creative reinterpretation')
      challenges.push('High production values expected by audience')
      opportunities.push('Blockbuster potential if executed well')
      opportunities.push('Opens premium licensing opportunities')
    } else if (matrix.difficulty === 'complex') {
      challenges.push('Medium-specific narrative techniques required')
      challenges.push('Fan expectations create quality bar pressure')
      opportunities.push('Strong audience crossover potential')
      opportunities.push('Can leverage existing fanbase for launch')
    } else if (matrix.difficulty === 'moderate') {
      challenges.push('Some creative adaptation needed')
      opportunities.push('Lower barrier to entry, faster time-to-market')
      opportunities.push('Can test market response before larger investments')
    } else {
      challenges.push('Relatively direct adaptation path')
      opportunities.push('Quickest path to revenue')
      opportunities.push('Low investment, minimal risk experiment')
    }

    if (target === 'game') {
      opportunities.push('Games offer ongoing revenue via DLC, in-app purchases')
      challenges.push('Game design requires separate skill set from original medium')
    }
    if (target === 'animation') {
      opportunities.push('Animation has strong streaming platform demand')
      challenges.push('Production quality expectations are high for animation')
    }
    if (target === 'merchandise') {
      opportunities.push('Merchandise: low margin but high fan engagement')
    }

    adaptationPath.push({
      from_medium: source,
      to_medium: target,
      difficulty: matrix.difficulty,
      estimated_cost_usd: cost,
      estimated_timeline_months: time,
      key_challenges: challenges,
      opportunities,
    })
  }

  const totalCost = adaptationPath.reduce((s, a) => s + a.estimated_cost_usd, 0)
  const totalTimeline = Math.max(...adaptationPath.map(a => a.estimated_timeline_months))

  let riskAssessment = 'Manageable'
  if (totalCost > budget * 2) riskAssessment = 'High risk — significant budget overrun likely'
  else if (totalCost > budget) riskAssessment = 'Elevated risk — budget stretched'
  else if (adaptationPath.some(a => a.difficulty === 'very_complex')) riskAssessment = 'Moderate risk — complex adaptations require careful planning'

  return {
    adaptation_path: adaptationPath,
    total_cost: totalCost,
    total_timeline: totalTimeline,
    risk_assessment: riskAssessment,
    summary: `${ipTitle} (${source}) | ${adaptationPath.length} target media | Total cost: $${totalCost.toLocaleString()} | Timeline: ${totalTimeline} months | Risk: ${riskAssessment}`,
  }
}

