function formatClauseExtractionReport(r: ClauseExtractorResult): string {
  const lines: string[] = []
  lines.push('# Contract Clause Extraction Report')
  lines.push('## Extraction Summary')
  lines.push('- Extraction ID: ' + r.extraction_id)
  lines.push('- Contract Type: ' + r.contract_type)
  lines.push('- Clauses Found: ' + r.clauses_found)
  lines.push('- Coverage: ' + r.coverage_pct + '%')
  lines.push('## Clause Categories')
  for (const c of r.clause_categories) lines.push('- ' + c.category.replace(/_/g, ' ') + ': ' + c.count + ' clause(s)')
  if (r.risk_flags.length > 0) {
    lines.push('## Risk Flags')
    for (const rf of r.risk_flags) lines.push('- **' + rf.clause_id + '** [' + rf.risk + ']: ' + rf.description)
  }
  lines.push('---')
  lines.push(DISCLAIMER)
  return lines.join('\n')
}

