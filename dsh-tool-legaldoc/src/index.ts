  const varFieldNames = ['Effective Date', 'Party A Name', 'Party A Address', 'Party B Name', 'Party B Address', 'Contract Value', 'Payment Schedule', 'Governing Law Jurisdiction', 'Notice Address', 'Term Length', 'Renewal Period', 'Termination Notice Period', 'Liability Cap Amount', 'Insurance Requirement', 'Dispute Resolution Venue']
  for (let i = 0; i < Math.min(variableFields, varFieldNames.length); i++) { lines.push('| ' + varFieldNames[i] + ' | text | yes |') }
  lines.push('---')
  lines.push('*Generated by DSH Legal Document Automation Toolkit v' + VERSION + '*')
  return {
    template_id: 'TMPL-' + Math.floor(rand() * 0xFFFFFFFF).toString(16).toUpperCase().slice(0, 8),
    template_name: templateName, sections_count: sectionsCount,
    variable_fields: variableFields, clause_count: clauseCount, template_content: lines.join('\n')
  }
