function aggregateThreatIntel(input: ThreatIntelInput): ThreatIntelResult {
  const rng = createRngFromInput(input)
  const aggregationId = `TI-${randInt(rng, 10000, 99999)}`

  const iocTypes = ['IP Address', 'Domain', 'File Hash (SHA256)', 'URL', 'Email Address', 'CVE', 'Mutex', 'Registry Key', 'Certificate Hash', 'YARA Rule']
  const severities = ['Critical', 'High', 'Medium', 'Low']
  const sources = input.sources.length > 0 ? input.sources : ['AlienVault OTX', 'VirusTotal', 'MISP', 'Shodan', 'Abuse.ch', 'CISA KEV', 'Recorded Future', 'ThreatConnect']
  const campaigns = ['APT28-Fancy Bear', 'APT29-Cozy Bear', 'Lazarus Group', 'Equation Group', 'Carbanak', 'CozyDuke', 'Sandworm', 'Turla', 'Kimsuky', 'MuddyWater']
  const mitreTechniques = ['T1566-Phishing', 'T1059-Command Scripting', 'T1078-Valid Accounts', 'T1105-Ingress Tool Transfer', 'T1048-Exfiltration', 'T1486-Data Encrypted', 'T1562-Impair Defenses', 'T1021-Remote Services', 'T1003-Credential Dumping', 'T1053-Scheduled Task']

  const indicatorCount = randInt(rng, 8, 25)
  const indicators: ThreatIndicator[] = []
  for (let i = 0; i < indicatorCount; i++) {
    const iocType = pick(rng, iocTypes)
    let ioc = ''
    switch (iocType) {
      case 'IP Address': ioc = `${randInt(rng, 1, 255)}.${randInt(rng, 0, 255)}.${randInt(rng, 0, 255)}.${randInt(rng, 1, 255)}`; break
      case 'Domain': ioc = `mal${randInt(rng, 100, 999)}-${pick(rng, ['c2', 'drop', 'update', 'cdn'])}.${pick(rng, ['xyz', 'top', 'club', 'online', 'site'])}`; break
      case 'File Hash (SHA256)': ioc = Array.from({ length: 64 }, () => '0123456789abcdef'[randInt(rng, 0, 15)]).join(''); break
      case 'URL': ioc = `https://mal-${randInt(rng, 100, 999)}.${pick(rng, ['xyz', 'top', 'club'])}/${pick(rng, ['update', 'download', 'api', 'gate'])}.php`; break
      case 'Email Address': ioc = `actor${randInt(rng, 1, 99)}@${pick(rng, ['protonmail.com', 'tutanota.com', 'gmail.com'])}`; break
      case 'CVE': ioc = `CVE-2025-${randInt(rng, 10000, 99999)}`; break
      default: ioc = `indicator-${randInt(rng, 100000, 999999)}`; break
    }

    const sevIdx = randInt(rng, 0, 3)
    const severityThresholdIdx = input.severity_threshold === 'all' ? 3 : severities.indexOf(input.severity_threshold.charAt(0).toUpperCase() + input.severity_threshold.slice(1))
    const severity = severityThresholdIdx < sevIdx ? severities[sevIdx] : severities[Math.min(sevIdx, severityThresholdIdx)]

    indicators.push({
      ioc,
      type: iocType,
      severity,
      confidence: Math.round((0.5 + rng() * 0.5) * 100) / 100,
      source: pick(rng, sources),
      first_seen: `2025-${String(randInt(rng, 1, 7)).padStart(2, '0')}-${String(randInt(rng, 1, 28)).padStart(2, '0')}`,
      last_seen: `2025-${String(randInt(rng, 8, 12)).padStart(2, '0')}-${String(randInt(rng, 1, 28)).padStart(2, '0')}`,
      related_campaigns: pickN(rng, campaigns, randInt(rng, 1, 3)),
      mitre_technique: pick(rng, mitreTechniques),
    })
  }

  const actorCount = randInt(rng, 3, 7)
  const motivations = ['Cybercrime', 'Espionage', 'Hacktivism', 'Destructive', 'Financial Theft', 'State-Sponsored']
  const sophisticationLevels = ['Low', 'Moderate', 'High', 'Advanced Persistent', 'Elite']
  const origins = ['CN', 'RU', 'KP', 'IR', 'Unknown', 'Eastern Europe', 'Southeast Asia']
  const sectors = ['Finance', 'Healthcare', 'Government', 'Energy', 'Technology', 'Defense', 'Telecom', 'Manufacturing', 'Education', 'Critical Infrastructure']
  const tools = ['Cobalt Strike', 'Metasploit', 'Mimikatz', 'PowerShell Empire', 'Cobalt Beacon', 'Custom RAT', 'Living-off-Land', 'Fileless Malware', 'Supply Chain Compromise', 'Zero-Day Exploit']

  const threatActors: ThreatActor[] = []
  for (let i = 0; i < actorCount; i++) {
    threatActors.push({
      name: pick(rng, campaigns) + `-${randInt(rng, 1, 99)}`,
      motivation: pick(rng, motivations),
      sophistication: pick(rng, sophisticationLevels),
      origin: pick(rng, origins),
      targeted_sectors: pickN(rng, sectors, randInt(rng, 2, 4)),
      known_tools: pickN(rng, tools, randInt(rng, 2, 5)),
      active: rng() > 0.3,
    })
  }

  const campaignCorrelations: string[] = []
  const selectedCampaigns = pickN(rng, campaigns, randInt(rng, 3, 5))
  for (const camp of selectedCampaigns) {
    campaignCorrelations.push(`${camp}: ${randInt(rng, 3, 15)} correlated indicators detected in ${input.industry} sector`)
  }

  const trendAnalysis: string[] = []
  trendAnalysis.push(`Phishing campaigns targeting ${input.industry} increased ${randInt(rng, 15, 65)}% in the last ${input.time_window_days} days`)
  trendAnalysis.push(`Ransomware variants targeting ${input.industry}: ${randInt(rng, 5, 20)} new families identified`)
  trendAnalysis.push(`Zero-day exploits observed: ${randInt(rng, 1, 8)} in the analysis window`)
  trendAnalysis.push(`Credential stuffing attacks from ${pick(rng, origins)}-based infrastructure: ${randInt(rng, 100, 2000)} attempts/day`)
  trendAnalysis.push(`Supply chain compromise attempts: ${randInt(rng, 0, 5)} detected via dependency monitoring`)

  const recommendedActions: string[] = []
  recommendedActions.push(`Block ${indicators.filter(i => i.type === 'IP Address').length} identified malicious IPs at perimeter firewall`)
  recommendedActions.push(`Deploy IOCs to SIEM for real-time detection (${indicators.length} indicators)`)
  recommendedActions.push(`Update email filtering rules for ${indicators.filter(i => i.type === 'Email Address').length} malicious sender patterns`)
  recommendedActions.push(`Patch systems against ${indicators.filter(i => i.type === 'CVE').length} identified CVEs`)
  recommendedActions.push(`Conduct threat hunt for TTPs associated with ${threatActors.filter(a => a.active).length} active threat actors`)
  recommendedActions.push(`Brief executive leadership on ${input.industry}-specific threat landscape`)

  const criticalCount = indicators.filter(i => i.severity === 'Critical').length
  const highCount = indicators.filter(i => i.severity === 'High').length
  let riskLevel: ThreatIntelResult['risk_level'] = 'Low'
  if (criticalCount >= 3) riskLevel = 'Critical'
  else if (criticalCount >= 1 || highCount >= 5) riskLevel = 'High'
  else if (highCount >= 2) riskLevel = 'Medium'

  return {
    organization: input.organization,
    industry: input.industry,
    aggregation_id: aggregationId,
    time_window_days: input.time_window_days,
    total_indicators: indicators.length,
    indicators,
    threat_actors: threatActors,
    campaign_correlations: campaignCorrelations,
    trend_analysis: trendAnalysis,
    recommended_actions: recommendedActions,
    risk_level: riskLevel,
  }
}

function formatThreatIntelReport(r: ThreatIntelResult): string {
  const lines: string[] = []
  lines.push('## Threat Intelligence Aggregation Report')
  lines.push('')
  lines.push(`**Organization:** ${r.organization} | **Industry:** ${r.industry} | **Aggregation ID:** ${r.aggregation_id}`)
  lines.push(`**Time Window:** ${r.time_window_days} days | **Total Indicators:** ${r.total_indicators} | **Risk Level:** ${r.risk_level}`)
  lines.push('')
  lines.push('### Key Indicators of Compromise')
  lines.push('| IOC | Type | Severity | Confidence | Source | MITRE |')
  lines.push('|-----|------|----------|------------|--------|-------|')
  for (const i of r.indicators.slice(0, 15)) {
    lines.push(`| ${i.ioc.substring(0, 40)} | ${i.type} | ${i.severity} | ${(i.confidence * 100).toFixed(0)}% | ${i.source} | ${i.mitre_technique} |`)
  }
  if (r.indicators.length > 15) lines.push(`| ... and ${r.indicators.length - 15} more indicators | | | | | |`)
  lines.push('')
  lines.push('### Threat Actors')
  for (const a of r.threat_actors) {
    lines.push(`- **${a.name}** [${a.sophistication}] | Origin: ${a.origin} | Motivation: ${a.motivation} | Active: ${a.active ? 'Yes' : 'No'}`)
    lines.push(`  - Targets: ${a.targeted_sectors.join(', ')}`)
    lines.push(`  - Tools: ${a.known_tools.join(', ')}`)
  }
  lines.push('')
  lines.push('### Campaign Correlations')
  for (const c of r.campaign_correlations) lines.push(`- ${c}`)
  lines.push('')
  lines.push('### Trend Analysis')
  for (const t of r.trend_analysis) lines.push(`- ${t}`)
  lines.push('')
  lines.push('### Recommended Actions')
  for (const a of r.recommended_actions) lines.push(`- [ ] ${a}`)
  lines.push('')
  lines.push(`> **Disclaimer:** ${DISCLAIMER}`)
  return lines.join('\n')
}

