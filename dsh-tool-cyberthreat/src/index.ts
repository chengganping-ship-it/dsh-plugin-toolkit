function runVulnManagement(input: VulnMgmtInput): VulnMgmtResult {
  const rng = createRngFromInput(input)
  const scanId = `VULN-${randInt(rng, 10000, 99999)}`

  const vulnTemplates = [
    { desc: 'Remote Code Execution via deserialization', cvss: 9.8, sev: 'Critical' as const },
    { desc: 'SQL Injection in authentication endpoint', cvss: 9.1, sev: 'Critical' as const },
    { desc: 'Server-Side Request Forgery (SSRF)', cvss: 8.6, sev: 'High' as const },
    { desc: 'Cross-Site Scripting (Stored)', cvss: 7.5, sev: 'High' as const },
    { desc: 'Privilege Escalation via misconfigured IAM', cvss: 8.2, sev: 'High' as const },
    { desc: 'Insecure Direct Object Reference (IDOR)', cvss: 7.8, sev: 'High' as const },
    { desc: 'XML External Entity (XXE) Injection', cvss: 8.4, sev: 'High' as const },
    { desc: 'Path Traversal in file upload', cvss: 7.2, sev: 'High' as const },
    { desc: 'Weak TLS configuration (TLS 1.0 enabled)', cvss: 5.9, sev: 'Medium' as const },
    { desc: 'Missing security headers (CSP/HSTS)', cvss: 4.3, sev: 'Medium' as const },
    { desc: 'Information disclosure via error messages', cvss: 5.3, sev: 'Medium' as const },
    { desc: 'Outdated library with known CVE', cvss: 6.5, sev: 'Medium' as const },
    { desc: 'Default credentials on admin panel', cvss: 9.5, sev: 'Critical' as const },
    { desc: 'Unauthenticated API endpoint exposure', cvss: 7.1, sev: 'High' as const },
    { desc: 'Container escape via privileged mode', cvss: 8.9, sev: 'Critical' as const },
    { desc: 'Kubernetes RBAC misconfiguration', cvss: 7.4, sev: 'High' as const },
    { desc: 'Cloud storage bucket public access', cvss: 6.8, sev: 'Medium' as const },
    { desc: 'Insecure secrets in environment variables', cvss: 7.9, sev: 'High' as const },
    { desc: 'Missing MFA on privileged accounts', cvss: 8.1, sev: 'High' as const },
    { desc: 'Log injection vulnerability', cvss: 4.8, sev: 'Medium' as const },
  ]

  const assets = input.asset_scope.length > 0 ? input.asset_scope : ['web-app-01', 'api-gateway', 'db-primary', 'k8s-cluster', 'cdn-edge', 'auth-service']
  const maxResults = input.max_results || randInt(rng, 10, 20)
  const vulnCount = Math.min(maxResults, randInt(rng, 8, vulnTemplates.length))

  const vulnerabilities: Vulnerability[] = []
  const selectedTemplates = pickN(rng, vulnTemplates, vulnCount)
  for (const tpl of selectedTemplates) {
    const cvssVariance = (rng() * 1.4) - 0.7
    const cvss = Math.max(0, Math.min(10, tpl.cvss + cvssVariance))
    const severity = cvss >= 9.0 ? 'Critical' : cvss >= 7.0 ? 'High' : cvss >= 4.0 ? 'Medium' : 'Low'
    const exploitAvailable = input.include_exploitability && (cvss >= 7.0 ? rng() > 0.3 : rng() > 0.7)

    vulnerabilities.push({
      cve_id: `CVE-2025-${randInt(rng, 10000, 99999)}`,
      cvss_score: Math.round(cvss * 10) / 10,
      severity,
      asset: pick(rng, assets),
      description: tpl.desc,
      exploit_available: exploitAvailable,
      patch_available: rng() > 0.25,
      remediation_effort: cvss >= 9.0 ? 'High' : cvss >= 7.0 ? (rng() > 0.5 ? 'Medium' : 'High') : 'Low',
      days_open: randInt(rng, 1, 180),
      epss_score: Math.round((rng() * (cvss / 10)) * 100) / 100,
    })
  }

  const bySeverity: Record<string, number> = { Critical: 0, High: 0, Medium: 0, Low: 0 }
  for (const v of vulnerabilities) bySeverity[v.severity]++

  const remediationPlan: string[] = []
  const criticalVulns = vulnerabilities.filter(v => v.severity === 'Critical')
  const highVulns = vulnerabilities.filter(v => v.severity === 'High')
  const exploitable = vulnerabilities.filter(v => v.exploit_available)

  if (criticalVulns.length > 0) {
    remediationPlan.push(`IMMEDIATE (24hr): Patch ${criticalVulns.length} Critical vulnerabilities: ${criticalVulns.slice(0, 3).map(v => v.cve_id).join(', ')}`)
  }
  if (exploitable.length > 0) {
    remediationPlan.push(`URGENT (48hr): Address ${exploitable.length} exploitable vulnerabilities with public PoC/exploit code`)
  }
  if (highVulns.length > 0) {
    remediationPlan.push(`HIGH (7 days): Remediate ${highVulns.length} High-severity vulnerabilities`)
  }
  remediationPlan.push(`STANDARD (30 days): Address ${vulnerabilities.filter(v => v.severity === 'Medium').length} Medium-severity findings`)
  remediationPlan.push(`PLANNED (90 days): Resolve ${vulnerabilities.filter(v => v.severity === 'Low').length} Low-severity findings via regular patching cycle`)
  remediationPlan.push(`Process: Implement continuous vulnerability scanning with weekly reporting cadence`)

  const complianceGaps: string[] = []
  if (criticalVulns.length > 0) complianceGaps.push('SOC2 CC7.1: Critical vulnerabilities exceed 24-hour remediation SLA')
  if (vulnerabilities.filter(v => v.days_open > 30).length > 3) complianceGaps.push('PCI DSS Req 6.2: Multiple vulnerabilities past 30-day remediation window')
  if (vulnerabilities.filter(v => !v.patch_available).length > 0) complianceGaps.push('ISO27001 A.12.6.1: Unpatched vulnerabilities require risk acceptance documentation')
  if (input.environment === 'cloud' && vulnerabilities.some(v => v.description.includes('bucket') || v.description.includes('RBAC'))) {
    complianceGaps.push('CSA CCM: Cloud security configuration gaps identified')
  }

  const riskAcceptanceItems: string[] = []
  const unpatched = vulnerabilities.filter(v => !v.patch_available)
  for (const v of unpatched.slice(0, 3)) {
    riskAcceptanceItems.push(`${v.cve_id} on ${v.asset}: No patch available - compensating controls required`)
  }

  const avgDaysOpen = vulnerabilities.reduce((s, v) => s + v.days_open, 0) / vulnerabilities.length
  const mttrEstimate = avgDaysOpen > 60 ? '60+ days (process improvement needed)' : avgDaysOpen > 30 ? '30-60 days' : '14-30 days'

  return {
    scan_id: scanId,
    environment: input.environment,
    scan_depth: input.scan_depth,
    total_vulnerabilities: vulnerabilities.length,
    by_severity: bySeverity,
    vulnerabilities,
    remediation_plan: remediationPlan,
    compliance_gaps: complianceGaps,
    risk_acceptance_items: riskAcceptanceItems,
    mttr_estimate: mttrEstimate,
  }
}

function formatVulnMgmtReport(r: VulnMgmtResult): string {
  const lines: string[] = []
  lines.push('## Vulnerability Management Report')
  lines.push('')
  lines.push(`**Scan ID:** ${r.scan_id} | **Environment:** ${r.environment} | **Scan Depth:** ${r.scan_depth}`)
  lines.push(`**Total Vulnerabilities:** ${r.total_vulnerabilities} | **MTTR Estimate:** ${r.mttr_estimate}`)
  lines.push('')
  lines.push('### Severity Breakdown')
  lines.push(`- Critical: ${r.by_severity.Critical} | High: ${r.by_severity.High} | Medium: ${r.by_severity.Medium} | Low: ${r.by_severity.Low}`)
  lines.push('')
  lines.push('### Top Vulnerabilities')
  lines.push('| CVE | CVSS | Severity | Asset | Exploit | Patch | EPSS |')
  lines.push('|-----|------|----------|-------|---------|-------|------|')
  for (const v of r.vulnerabilities.slice(0, 12)) {
    lines.push(`| ${v.cve_id} | ${v.cvss_score} | ${v.severity} | ${v.asset} | ${v.exploit_available ? 'Yes' : 'No'} | ${v.patch_available ? 'Yes' : 'No'} | ${v.epss_score} |`)
  }
  lines.push('')
  lines.push('### Remediation Plan')
  for (const p of r.remediation_plan) lines.push(`- ${p}`)
  lines.push('')
  if (r.compliance_gaps.length > 0) {
    lines.push('### Compliance Gaps')
    for (const g of r.compliance_gaps) lines.push(`- ${g}`)
    lines.push('')
  }
  if (r.risk_acceptance_items.length > 0) {
    lines.push('### Risk Acceptance Required')
    for (const item of r.risk_acceptance_items) lines.push(`- ${item}`)
    lines.push('')
  }
  lines.push(`> **Disclaimer:** ${DISCLAIMER}`)
  return lines.join('\n')
}

